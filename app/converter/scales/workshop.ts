const rows = (src: Array<[string, number]>): GaugeRow[] => src.map(([id, inch]) => ({ id, inch, mm: inch * IN }));
export const SWG = rows(SWG_INCH);
export const NUMBER_LETTER_DRILLS = rows(DRILL_INCH);

/** Kesirli inç matkaplar: 1/64" adımla 1/64"–1". Etiket sadeleştirilmiş kesirdir (8/64 → 1/8"). */
export const FRACTION_DRILLS: GaugeRow[] = Array.from({ length: 64 }, (_, i) => {
  let n = i + 1;
  let d = 64;
  while (n % 2 === 0 && d > 1) {
    n /= 2;
    d /= 2;
  }
  return { id: d === 1 ? `${n}"` : `${n}/${d}"`, inch: (i + 1) / 64, mm: ((i + 1) / 64) * IN };
});

/** Verilen mm değerine en yakın satır (mutlak farkla). */
export function nearest(table: GaugeRow[], mm: number): GaugeRow | null {
  if (!Number.isFinite(mm) || mm <= 0) return null;
  return table.reduce((best, r) => (Math.abs(r.mm - mm) < Math.abs(best.mm - mm) ? r : best));
}

/** 0,1 mm adımlı metrik matkap serisindeki en yakın uç. */
export const nearestMetricDrill = (mm: number) => Math.round(mm * 10 + 1e-9) / 10;
