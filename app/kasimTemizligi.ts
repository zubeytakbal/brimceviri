/** Yönlendirilen bir çiftin bugünkü adresi ve eski kök adresi (taşınan kategorilerde ikisi farklı). */
function ciftYollari(slug: string, kategori: string): string[] {
  return yeniYapiKategorileri.has(kategori) ? [`/${kategori}/${slug}`, `/${slug}`] : [`/${slug}`];
}

/** Bu temizlikte 301 ile yönlenen bütün adresler: [kaynak, hedef]. */
export function kasimYonlendirmeleri(): [string, string][] {
  const satirlar: [string, string][] = Object.entries(BIRLESEN_SAYFALAR);
  for (const [slug, kategori] of YONLENDIRILEN_CIFTLER) {
    for (const yol of ciftYollari(slug, kategori)) satirlar.push([yol, turkceKategoriYolu(kategori)]);
  }
  return satirlar;
}

let kalkanlar: Set<string> | undefined;
/** Sayfası artık yayında olmayan (silinen ya da yönlenen) adres mi? */
export function kasimdaKalkti(yol: string): boolean {
  kalkanlar ??= new Set([...SILINEN_SAYFALAR, ...kasimYonlendirmeleri().map(([kaynak]) => kaynak)]);
  return kalkanlar.has(yol);
}
